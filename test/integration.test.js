import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import WebSocket from 'ws';
import { createHost } from '../src/server.js';
import { startRunner } from '../src/runner.js';
import { insideRoot, repositoryUrl } from '../src/sync.js';

const wait = async predicate => { const end = Date.now() + 15000; while (!predicate()) { if (Date.now() > end) throw new Error('Timed out'); await new Promise(r => setTimeout(r, 50)); } };
test('host and remote runner launch a real PTY, route output/input, stop, and enforce permissions', { timeout: 30000 }, async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'relaydeck-e2e-'));
  let host = await createHost({ directory: dir, port: 0, local: false, quiet: true });
  let runner, browser;
  t.after(async () => { browser?.close(); runner?.stop(); await host.close(); await rm(dir, { recursive: true, force: true }); });
  const request = async (route, body, token = host.store.data.adminToken) => {
    const response = await fetch(`${host.address}/api${route}`, { method: body === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  };
  assert.equal((await request('/state', undefined, 'bad')).status, 401);
  const { data: d } = await request('/devices', { name: 'Remote test' });
  runner = await startRunner({ server: host.address, token: d.token, root: dir, log() {} });
  await wait(() => host.store.data.devices[0].online);
  const result = await request('/agents', { deviceId: d.id, name: 'Echo harness', harness: 'Node', command: process.execPath, args: ['-e', "console.log('HARNESS_READY');process.stdin.on('data',d=>console.log('ECHO:'+d.toString().trim()))"], cwd: dir }, d.token);
  assert.equal(result.status, 200); const agentId = result.data.id;
  await wait(() => host.store.data.agents[0].status === 'running');
  browser = new WebSocket(host.address.replace('http', 'ws') + '/ws', { headers: { Authorization: `Bearer ${d.token}` } });
  let output = ''; const errors = [];
  browser.on('message', data => { const m = JSON.parse(data); if (m.type === 'terminal') output += m.data; if (m.type === 'error') errors.push(m.error); });
  await new Promise(resolve => browser.once('open', resolve));
  browser.send(JSON.stringify({ type: 'subscribe', agentId }));
  await wait(() => output.includes('HARNESS_READY'));
  browser.send(JSON.stringify({ type: 'input', agentId, data: 'HELLO_TEAM\r' }));
  await wait(() => output.includes('ECHO:HELLO_TEAM'));
  const other = (await request('/devices', { name: 'Other client' })).data;
  assert.equal((await request(`/agents/${agentId}/stop`, {}, other.token)).status, 403);
  assert.equal((await request('/devices', { name: 'Forbidden' }, d.token)).status, 403);
  const addressPort = host.server.address().port;
  await host.close();
  host = await createHost({ directory: dir, port: addressPort, local: false, quiet: true });
  await wait(() => host.store.data.devices[0].online && host.store.data.agents[0].status === 'running');
  await request(`/agents/${agentId}/stop`, {}, d.token);
  await wait(() => host.store.data.agents[0].status === 'stopped');
  assert.deepEqual(errors, []);
  await request(`/agents/${agentId}/restart`, {}, d.token);
  await wait(() => host.store.data.agents[0].status === 'running');
  await request(`/agents/${agentId}/stop`, {}, d.token);
  await wait(() => host.store.data.agents[0].status === 'stopped');
});
test('workspace paths cannot escape and repository URLs reject embedded secrets', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'relaydeck-path-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  await mkdir(path.join(dir, 'project'));
  assert.equal(await insideRoot(dir, 'project'), path.join(dir, 'project'));
  await assert.rejects(() => insideRoot(dir, '..'), /inside/);
  assert.throws(() => repositoryUrl('https://secret:token@git.example/team/repo'), /credentials/);
  assert.throws(() => repositoryUrl('file:///tmp/repo'), /HTTP/);
  assert.equal(repositoryUrl('https://git.example/team/repo.git').api, 'https://git.example/api/v1/version');
});
