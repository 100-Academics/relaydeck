import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Store } from '../src/store.js';

test('removing a device removes its agents and related coordination data', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'relaydeck-device-'));
  const store = new Store(directory);
  t.after(async () => { store.close(); await rm(directory, { recursive: true, force: true }); });
  const host = { role: 'admin', id: 'human', name: 'Host' };
  const device = store.device('Laptop');
  const other = store.device('Other');
  store.data.devices[0].online = true;
  store.data.devices[1].online = true;
  const launched = store.agent(host, { deviceId: device.id, name: 'Agent', harness: 'test', command: 'node', args: [], cwd: '.' });
  const agent = store.auth(launched.token);
  const launchedB = store.agent(host, { deviceId: other.id, name: 'Agent B', harness: 'test', command: 'node', args: [], cwd: '.' });
  const agentB = store.auth(launchedB.token);
  store.tool(host, 'group_notice', { body: 'Keep this room' });
  store.tool(host, 'council', { question: 'Pick a direction' });
  store.tool(agent, 'message', { to: 'human', body: 'Remove me' });
  store.tool(agentB, 'message', { to: agent.id, body: 'B to doomed' });
  store.tool(agentB, 'message', { to: 'human', body: 'B to host' });
  store.removeDevice(device.id);
  assert.equal(store.data.devices.some(d => d.id === device.id), false);
  assert.equal(store.data.agents.some(a => a.id === agent.id), false);
  assert.equal(store.data.agents.some(a => a.id === agentB.id), true);
  assert.equal(store.data.messages.some(m => m.from === agent.id), false);
  assert.equal(store.data.messages.some(m => m.body === 'Keep this room'), true, 'group room history must survive device removal');
  assert.equal(store.data.messages.some(m => m.body === 'B to doomed'), false, 'messages addressed to a removed agent are cleaned up');
  assert.equal(store.data.messages.some(m => m.body === 'B to host'), true, 'conversations between surviving members survive');
  assert.equal(store.data.councils.length, 1, 'a council started by the host survives device removal');
  assert.deepEqual(store.data.councils[0].participants, [agentB.id], 'council keeps its surviving participants');
  assert.equal(store.data.devices.some(d => d.id === other.id), true);
});
